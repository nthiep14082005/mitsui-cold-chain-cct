function makeTempSeries(params: {
  loggerId: string;
  startIso: string;
  count: number;
  stepMinutes: number;
  baseTemp: number;
  humidity?: number;
  spikeAtIndices?: number[];
  spikeTemp?: number;
  skipIndices?: number[];
}): TempReading[] {
  const {
    loggerId,
    startIso,
    count,
    stepMinutes,
    baseTemp,
    humidity = 91,
    spikeAtIndices = [],
    spikeTemp = 9.5,
    skipIndices = [],
  } = params;
  const startMs = new Date(startIso).getTime();
  const skipSet = new Set(skipIndices);
  const spikeSet = new Set(spikeAtIndices);
  const list: TempReading[] = [];

  for (let i = 0; i < count; i++) {
    if (skipSet.has(i)) continue;
    const ts = new Date(startMs + i * stepMinutes * 60000).toISOString();
    const jitter = ((i % 5) - 2) * 0.12;
    const tempC = spikeSet.has(i) ? spikeTemp : Math.round((baseTemp + jitter) * 100) / 100;
    list.push({
      id: `READ-${loggerId}-${startMs}-${i}`,
      loggerId,
      timestamp: ts,
      tempC,
      humidityPct: humidity + (i % 3),
      source: 'IOT',
      ingestedAt: ts,
    });
  }
  return list;
}

